#!/usr/bin/env bash
# Проверка синтаксиса всех модулей расширения в OneScript (oscript -check). Глобальные объекты и функции платформы 1С,
# которых нет в OneScript, объявляются заглушками в копии модуля: проверяется синтаксис, а не работа с метаданными.
set -euo pipefail
cd "$(dirname "$0")/.."
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

globals='Метаданные, Константы, Перечисления, ОТ_КлиентAPI, ОТ_ЧекиКонфигурации, ОТ_Обмен, УровеньЖурналаРегистрации, РегламентныеЗадания'
# Модуль формы: элементы и реквизиты формы обработки настроек.
form_globals='Элементы, Адрес, Ключ, Событие, ПолеТовара, ВыгружатьС, Состояние'
stubs='
Функция ТекущаяДатаСеанса() Возврат ТекущаяДата(); КонецФункции
Процедура ЗаписьЖурналаРегистрации(А, Б = Неопределено, В = Неопределено, Г = Неопределено, Д = Неопределено) КонецПроцедуры
Функция КраткоеПредставлениеОшибки(Инф) Возврат ""; КонецФункции
Функция ПодробноеПредставлениеОшибки(Инф) Возврат ""; КонецФункции
Процедура ПоказатьПредупреждение(А = Неопределено, Б = Неопределено) КонецПроцедуры
Процедура ПоказатьОповещениеПользователя(А = Неопределено, Б = Неопределено, В = Неопределено) КонецПроцедуры
Функция ОписаниеОповещения(А, Б) Возврат Неопределено; КонецФункции
'
status=0
while IFS= read -r -d '' module; do
    copy="$work/$(echo "$module" | tr '/' '_')"
    # Директивы компиляции (&НаКлиенте …) OneScript не знает — убираются, номера строк сохраняются.
    vars="$globals"
    [[ "$module" == */Forms/* ]] && vars="$globals, $form_globals"
    { printf 'Перем %s;\n' "$vars"; sed -E 's/^&На[^[:space:]]+$//' "$module"; printf '%s\n' "$stubs"; } > "$copy"
    if output=$(docker run --rm -v "$work":/w -w /w evilbeaver/onescript:latest oscript -check "/w/$(basename "$copy")" 2>&1) && [[ "$output" == *"No errors."* ]]; then
        echo "ok   $module"
    else
        echo "FAIL $module (строка в копии на 1 больше):"; echo "$output" | head -5; status=1
    fi
done < <(find src -name '*.bsl' -print0 | sort -z)
exit $status
